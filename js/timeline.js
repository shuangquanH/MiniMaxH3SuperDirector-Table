function normalizeState(raw) {
  const base = emptyState();
  if (!raw || typeof raw !== "object") return base;
  base.selection.start = Math.max(0, num(raw.selection?.start, 0));
  base.selection.duration = Math.max(5 / 24, num(raw.selection?.duration, 5));
  base.videoAudioEnabled = raw.videoAudioEnabled !== false;
  base.videoClips = Array.isArray(raw.videoClips) ? raw.videoClips.filter(x => x?.file).map(c => ({
    id: c.id || uid(), file: c.file, name: c.name || c.file.split(/[\\/]/).pop(), start: Math.max(0, num(c.start)),
    duration: Math.max(5 / 24, num(c.duration, 5)), trimStart: Math.max(0, num(c.trimStart)),
    sourceDuration: Math.max(0, num(c.sourceDuration, c.duration)), hasAudio: c.hasAudio !== false,
    referenceMode: ["guide","edit","boundary"].includes(c.referenceMode) ? c.referenceMode : "guide",
    referenceWidth: num(c.referenceWidth) > 0 ? alignReferenceDimension(c.referenceWidth) : 0,
    referenceHeight: num(c.referenceHeight) > 0 ? alignReferenceDimension(c.referenceHeight) : 0,
    sourceWidth: Math.max(0, Math.round(num(c.sourceWidth, 0))),
    sourceHeight: Math.max(0, Math.round(num(c.sourceHeight, 0))),
    proxy: c.proxy || "",
    peaks: Array.isArray(c.peaks) ? c.peaks : [],
  })) : [];
  base.images = Array.isArray(raw.images) ? raw.images.filter(x => x?.file).map(a => ({ id:a.id || uid(), ...a })) : [];
  // Audio is always a prompt-addressable reference in this copy: the "keep the
  // original waveform" mode needs a finite-segment sampler that is not part of
  // this package, so a saved locked flag is dropped on load.
  base.audios = Array.isArray(raw.audios) ? raw.audios.filter(x => x?.file).map(a => {
    const { audioMode, ...rest } = a;
    return { ...rest, id: a.id || uid() };
  }) : [];
  const rawConfig=raw.segmentConfig&&typeof raw.segmentConfig==="object"?raw.segmentConfig:{};
  const count=clamp(Math.floor(num(rawConfig.count,0)),1,64);
  const sourceSegments=Array.isArray(rawConfig.segments)?rawConfig.segments:[];
  const defaultWindows=createWindows([],count,base.selection.duration*24);
  base.segmentConfig={count,activeIndex:clamp(Math.floor(num(rawConfig.activeIndex)),0,count-1),mode:"timeline",segments:Array.from({length:count},(_,index)=>{
    const segment=sourceSegments[index]&&typeof sourceSegments[index]==="object"?sourceSegments[index]:{};
    const fallback=defaultWindows[index];
    // Whitelist the window: older builds stored per-segment material ids and a
    // per-segment prompt here, none of which this single-node copy consumes.
    return {
      startFrame:Math.round(num(segment.startFrame,fallback.startFrame)),
      endFrame:Math.round(num(segment.endFrame,fallback.endFrame)),
    };
  })};
  return base;
}

function viewURL(relative) {
  const parts = String(relative).replace(/\\/g, "/").split("/");
  const filename = parts.pop();
  const params = new URLSearchParams({ filename, type: "input" });
  if (parts.length) params.set("subfolder", parts.join("/"));
  return api.apiURL(`/view?${params.toString()}`);
}

