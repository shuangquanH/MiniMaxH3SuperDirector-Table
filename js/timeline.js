let timelineMessages = { ...TIMELINE_EN };
let timelineLocalePromise;
const activeLocale = () => {
  const raw = app.ui?.settings?.getSettingValue?.("Comfy.Locale") || app.ui?.settings?.getSettingValue?.("Comfy.Locale.Language") || navigator.language || "en";
  return String(raw).toLowerCase().startsWith("zh") ? "zh" : "en";
};
async function ensureTimelineLocale() {
  if (!timelineLocalePromise) timelineLocalePromise = (async () => {
    try {
      const response = await api.fetchApi("/i18n");
      if (!response.ok) return;
      const translations = await response.json();
      const messages = translations?.[activeLocale()]?.MiniMaxH3TimelineDirector?.timeline;
      if (messages && typeof messages === "object") timelineMessages = { ...TIMELINE_EN, ...messages };
    } catch (error) { console.warn("[MiniMaxH3TimelineDirector] Unable to load localization", error); }
  })();
  return timelineLocalePromise;
}
function tr(key, values = {}) {
  const english = TIMELINE_EN[key];
  let message = timelineMessages[key];
  // The server caches /i18n at startup, so a key added while ComfyUI is running
  // comes back missing or as the English default. Use the bundled Chinese text
  // in that case; a real translation from /i18n always wins.
  if ((message === undefined || message === english)
    && activeLocale() === "zh"
    && TIMELINE_ZH_SUPPLEMENT[key] !== undefined) {
    message = TIMELINE_ZH_SUPPLEMENT[key];
  }
  return String(message ?? english ?? key).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
}

// ComfyUI ignores canvas shortcuts while the target is editable and the panel
// swallows keydown on purpose, so Ctrl+S inside the prompt used to fall through
// to the browser's "save page" dialog. Re-issue the workflow save ourselves.
// Middle-drag pans the canvas everywhere else; inside the node panel the
// widget swallows pointer events, so the canvas never sees them. Drive the
// transform ourselves for the duration of the drag instead of trying to replay
// the gesture into litegraph's internal state machine.
function beginCanvasPan(event) {
  const canvas = globalThis.app?.canvas;
  // ds.offset is a typed vector, not a plain array: index it instead of testing
  // for Array.isArray, which used to make this bail out silently.
  if (!canvas?.ds || typeof canvas.ds.offset?.[0] !== "number") return false;
  event.preventDefault();
  event.stopPropagation();
  const start = { x: event.clientX, y: event.clientY };
  const origin = [canvas.ds.offset[0], canvas.ds.offset[1]];
  // A middle-drag is a canvas gesture, not an edit: it ends an active prompt edit
  // (the box goes back to its decorated idle state) and never starts one — only a
  // left click puts the caret back in.
  const activeAtPress = document.activeElement;
  if (activeAtPress?.classList?.contains?.("m3td-prompt-rich")) activeAtPress.blur();
  const scale = Number(canvas.ds.scale) || 1;
  const move = moveEvent => {
    if (moveEvent.buttons === 0) { finish(); return; }
    canvas.ds.offset[0] = origin[0] + (moveEvent.clientX - start.x) / scale;
    canvas.ds.offset[1] = origin[1] + (moveEvent.clientY - start.y) / scale;
    canvas.setDirty?.(true, true);
    moveEvent.preventDefault();
  };
  const finish = cancelEvent => {
    window.removeEventListener("pointermove", move, true);
    window.removeEventListener("pointerup", finish, true);
    window.removeEventListener("pointercancel", finish, true);
    document.body.style.removeProperty("cursor");
    // ComfyUI forwards the middle press to the canvas, which then believes it is
    // still dragging because the matching release happens over the widget. Give
    // it the release it is waiting for so the next click is not treated as a pan.
    try {
      const point = cancelEvent || {};
      canvas.processMouseUp?.({
        button: 1, buttons: 0, which: 2,
        clientX: point.clientX ?? 0, clientY: point.clientY ?? 0,
        preventDefault() {}, stopPropagation() {}, target: canvas.canvas,
      });
    } catch (error) {
      console.warn("[MiniMaxH3TimelineDirector] Unable to clear the canvas drag state", error);
    }
  };
  window.addEventListener("pointermove", move, true);
  window.addEventListener("pointerup", finish, true);
  window.addEventListener("pointercancel", finish, true);
  document.body.style.cursor = "grabbing";
  return true;
}

function handlePanelSaveShortcut(event) {
  if (!(event.ctrlKey || event.metaKey) || event.altKey) return false;
  if (String(event.key || "").toLowerCase() !== "s") return false;
  event.preventDefault();
  event.stopPropagation();
  const saveAs = event.shiftKey === true;
  const commands = globalThis.app?.extensionManager?.command;
  if (typeof commands?.execute === "function") {
    commands.execute(saveAs ? "Comfy.SaveWorkflowAs" : "Comfy.SaveWorkflow");
    return true;
  }
  // Older builds only expose the DOM binding, so replay the keys on a
  // non-editable target where the canvas shortcut handler will accept them.
  document.body?.dispatchEvent(new KeyboardEvent("keydown", {
    key: "s", code: "KeyS", ctrlKey: true, shiftKey: saveAs, bubbles: true, cancelable: true,
  }));
  return true;
}

// ComfyUI decides whether the tab shows a "modified" dot by diffing a serialized
// snapshot of the graph, and it only takes that snapshot when a native widget
// reports a change. The panel writes widget values directly, so typing in the
// prompt used to leave the workflow looking clean until some other click asked
// for a snapshot. Take one ourselves: immediately for the first change, then
// again once editing pauses so undoing back to the saved text clears the dot.
let workflowSnapshotTimer = 0;
let workflowSnapshotAt = 0;
let workflowEditedSinceLoad = false;
function markWorkflowModified() {
  workflowEditedSinceLoad = true;
  const capture = () => {
    workflowSnapshotAt = Date.now();
    try {
      globalThis.app?.extensionManager?.workflow?.activeWorkflow?.changeTracker?.captureCanvasState?.();
    } catch (error) {
      console.warn("[MiniMaxH3TimelineDirector] Unable to flag the workflow as modified", error);
    }
  };
  if (Date.now() - workflowSnapshotAt > 200) capture();
  clearTimeout(workflowSnapshotTimer);
  workflowSnapshotTimer = setTimeout(() => { workflowSnapshotTimer = 0; capture(); }, 350);
}

// The panel sizes the node to fit its own layout right after a workflow loads.
// Node size is part of the serialized graph, so that adjustment alone makes the
// tab look modified as soon as anything asks for a snapshot. Rebase the change
// tracker once the layout has settled, and only while the user has not touched
// anything yet, so real edits still show the dot immediately.
function rebaseWorkflowSnapshot() {
  const tracker = globalThis.app?.extensionManager?.workflow?.activeWorkflow?.changeTracker;
  const graph = globalThis.app?.graph?.rootGraph ?? globalThis.app?.graph;
  if (typeof tracker?.reset !== "function" || typeof graph?.serialize !== "function") return false;
  try {
    const snapshot = JSON.parse(JSON.stringify(graph.serialize()));
    tracker.reset(snapshot);
    tracker.updateModified?.(snapshot);
    return true;
  } catch (error) {
    console.warn("[MiniMaxH3TimelineDirector] Unable to rebase the workflow baseline", error);
    return false;
  }
}

