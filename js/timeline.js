// ---- Rich prompt decorations -------------------------------------------------
// The director prompt is plain text. These helpers find the H3 markers inside it
// so the editor can paint them apart from prose:
//   <Picture 1> / <Video 1> / <Audio 1>   media chips (with a thumbnail)
//   <Subject 1> / [Shot 1] / [English]    plain tags
//   (S1) / (S1,S2)                        speaker IDs
//   <d> </d> <scenetrans> <cutoff>        dialogue control markers
//   fully_preserved / reference ...       retention values (fixed English words)
//   Push In / at slow speed ...           fixed camera vocabulary
//   subject_definitions: ...              section headers
// Every matcher below must fire no matter what sits in front of the marker. A
// tag typed straight after a word ("参考<Picture 1>", "photo(S1)", "xxxPicture 1")
// used to stay unlit until a space was inserted, which read as "highlighting is
// broken". Only the trailing side keeps a boundary check so a longer word such
// as "Picture1x" is not eaten.
// Bracketed tags always match.  The shorthand without brackets must not eat
// prose such as "Video 2 seconds", "Video 2fps" or "视频2秒", so a trailing
// unit keeps the number out of the chip.
const PROMPT_MEDIA_RE = /<\s*(Picture|Image|Video|Audio|图片|图像|图|视频|音频)\s*#?\s*(\d+)\s*>|(Picture|Image|Video|Audio)\s*#?\s*(\d+)\b(?!\s*(?:>|s\b|sec(?:ond)?s?\b|fps\b|frames?\b|min(?:ute)?s?\b|ms\b|h(?:r|our)s?\b|times?\b|×|x\b|%))|(图片|图像|图|视频|音频)\s*#?\s*(\d+)(?!\s*(?:[秒帧个分时倍次张段]|小时|分钟|秒钟|帧率))/gi;
// Section headers may follow punctuation or prose on the same line; only a
// letter/digit touching the name disqualifies it (that would be another word).
const PROMPT_SECTION_RE = /(?<![A-Za-z0-9_])(?:subject_definitions|integrated_multimodal_description|summary|retention_analysis|detailed_description|overall_soundscape|non_diegetic_music)\s*[:：]/gi;
const PROMPT_DIALOGUE_RE = /<d>\s*\[[^\]\r\n]+\]([\s\S]*?)<\/d>/gi;
// Compound speakers are written "(S1,S2)" in the guide; the commas keep no space.
const PROMPT_SPEAKER_RE = /\(\s*S\d+(?:\s*,\s*S\d+)*\s*\)(?![A-Za-z0-9_])/gi;
const PROMPT_CONTROL_RE = /<\/?d>|<scenetrans>|<cutoff>/gi;
// Retention values sit right after the label colon and are followed by " - ...".
const PROMPT_STATE_RE = /[:：][ \t]*(fully_preserved|partially_preserved|attribute_transfer|weak_reference|fully_copy|partially_copy|reference)[ \t]*[-–—]/gi;
// Camera motion is prose ("The camera pulls back..."), so matching the table's
// original labels only ever caught the amplitude/speed phrases. Tint the whole
// clause that starts with "the camera" instead: it does not care how the verb is
// inflected.
const PROMPT_CAMERA_RE = /\bthe camera\b[^.!?\n]*/gi;

// Higher priority wins when two rules cover the same characters: a media label
// beats the generic "<...>" tag rule, a control marker beats it too.
const PROMPT_DECORATION_PRIORITY = { media: 6, control: 5, tag: 4, state: 4, speaker: 4, camera: 3, section: 2, dialogue: 1 };

function promptPatternMatches(source, pattern, kind, group = 0) {
  const out = [];
  pattern.lastIndex = 0;
  let item;
  while ((item = pattern.exec(source))) {
    const raw = group ? item[group] : item[0];
    if (raw) {
      const index = item.index + item[0].indexOf(raw);
      out.push({ index, end: index + raw.length, raw, kind });
    }
    if (!item[0].length) pattern.lastIndex++;
  }
  return out;
}

function promptMediaMatches(source) {
  const matches = [];
  PROMPT_MEDIA_RE.lastIndex = 0;
  let item;
  while ((item = PROMPT_MEDIA_RE.exec(source))) {
    const label = String(item[1] || item[3] || item[5] || "").toLowerCase();
    const type = ["picture", "image", "图片", "图像", "图"].includes(label) ? "picture"
      : ["video", "视频"].includes(label) ? "video" : "audio";
    const ordinal = Number(item[2] || item[4] || item[6]);
    // H3 media ordinals start at 1; this also keeps "视频0.00秒" out of the chips.
    if (ordinal >= 1) matches.push({ index: item.index, end: item.index + item[0].length, raw: item[0], type, ordinal });
    if (!item[0].length) PROMPT_MEDIA_RE.lastIndex++;
  }
  return matches;
}

function promptTagMatches(source) {
  const media = promptMediaMatches(source);
  const overlaps = (start, end) => media.some(item => start < item.end && end > item.index);
  const out = [];
  const collect = (pattern, kind) => {
    for (const item of promptPatternMatches(source, pattern, kind)) {
      if (!overlaps(item.index, item.end)) out.push(item);
    }
  };
  // Tags keep their explicit brackets; plain prose is never decorated.
  collect(/<\/?[A-Za-z\u4e00-\u9fff][^<>\r\n]{0,80}>/g, "tag");
  collect(/\[[A-Za-z\u4e00-\u9fff][^\[\]\r\n]{0,80}\]/g, "tag");
  collect(PROMPT_SPEAKER_RE, "speaker");
  return out.sort((a, b) => a.index - b.index || b.end - a.end);
}

function promptCameraSegments(source, blocked) {
  const ranges = promptPatternMatches(source, PROMPT_CAMERA_RE, "camera");
  if (!ranges.length) return [];
  const ordered = [...blocked].sort((a, b) => a.index - b.index);
  const parts = [];
  for (const range of ranges) {
    let cursor = range.index;
    let end = range.end;
    for (const item of ordered) {
      if (item.end <= cursor) continue;
      if (item.index >= end) break;
      // A spoken line ends the clause: what follows belongs to the speech.
      if (item.kind === "dialogue" || item.kind === "control") {
        end = item.index;
        break;
      }
      if (item.index > cursor) parts.push({ index: cursor, end: item.index, kind: "camera" });
      cursor = Math.max(cursor, item.end);
    }
    if (cursor < end) parts.push({ index: cursor, end, kind: "camera" });
  }
  return parts
    .map(part => ({ ...part, raw: source.slice(part.index, part.end) }))
    .filter(part => part.raw.trim())
    .map(part => {
      // Keep the tint off the spaces around a split clause.
      const lead = part.raw.length - part.raw.trimStart().length;
      const trail = part.raw.length - part.raw.trimEnd().length;
      return { index: part.index + lead, end: part.end - trail, raw: part.raw.trim(), kind: "camera" };
    });
}

function promptDecorations(source) {
  const candidates = promptMediaMatches(source).map(item => ({ ...item, kind: "media" }));
  candidates.push(...promptTagMatches(source));
  candidates.push(...promptPatternMatches(source, PROMPT_CONTROL_RE, "control"));
  candidates.push(...promptPatternMatches(source, PROMPT_STATE_RE, "state", 1));
  candidates.push(...promptPatternMatches(source, PROMPT_SECTION_RE, "section"));
  PROMPT_DIALOGUE_RE.lastIndex = 0;
  let dialogue;
  while ((dialogue = PROMPT_DIALOGUE_RE.exec(source))) {
    const body = dialogue[1] || "";
    const index = dialogue.index + dialogue[0].indexOf(body);
    if (body) candidates.push({ index, end: index + body.length, raw: body, kind: "dialogue" });
    if (!dialogue[0].length) PROMPT_DIALOGUE_RE.lastIndex++;
  }
  candidates.sort((a, b) => a.index - b.index
    || PROMPT_DECORATION_PRIORITY[b.kind] - PROMPT_DECORATION_PRIORITY[a.kind]
    || b.end - a.end);
  // renderPromptEditor() only ever paints the first decoration covering a run of
  // characters, so anything that overlaps an already accepted span must be
  // dropped here as well or the repaint check would never agree with the DOM.
  const out = [];
  let cursor = -1;
  for (const item of candidates) {
    if (item.index < cursor) continue;
    out.push(item);
    cursor = item.end;
  }
  // Camera clauses are painted as a background tint, so they must never eat a
  // tag: every clause is split around the decorations already accepted above and
  // the plain remainders are tinted.
  const camera = promptCameraSegments(source, out);
  if (camera.length) out.push(...camera);
  out.sort((a, b) => a.index - b.index);
  // Reference labels that subject_definitions never introduced - including the
  // case-only typos like "<subject 1>" - are flagged so the editor can paint them
  // red right where they sit. Base-mode prompts have no definitions, so nothing
  // is flagged there.
  const defined = promptDefinedLabels(source);
  if (defined.size) {
    for (const item of out) {
      if (item.kind !== "tag" && item.kind !== "media") continue;
      const key = promptLabelKey(item.raw);
      if (/^<[A-Za-z]+ \d+>$/.test(key) && !defined.has(key)) item.missing = true;
    }
  }
  return out;
}

// Zero-width space used as a caret landing spot on an empty last line. It is
// never part of the prompt: every extraction and offset calculation strips it.
const PROMPT_CARET_ANCHOR = "\u200B";
const PROMPT_CARET_ANCHOR_PATTERN = /\u200B/g;
// The caret sentinel is a hidden <br> that only exists to keep the editor's last
// empty line alive, so it must never be mistaken for a real line break.
function promptSiblingBefore(node) {
  let previous = node.previousSibling;
  while (previous?.nodeType === Node.ELEMENT_NODE && previous.classList?.contains("m3td-prompt-caret-sentinel")) {
    previous = previous.previousSibling;
  }
  return previous;
}

function promptDomText(node) {
  if (!node) return "";
  if (node.nodeType === Node.TEXT_NODE) return node.data.replace(PROMPT_CARET_ANCHOR_PATTERN, "");
  if (node.nodeType !== Node.ELEMENT_NODE) return "";
  if (node.classList?.contains("m3td-prompt-media-preview") || node.classList?.contains("m3td-prompt-caret-sentinel")) return "";
  if (node.tagName === "BR") return "\n";
  const inner = [...node.childNodes].map(promptDomText).join("");
  // Chrome still emits paragraph wrappers for drag-drop, autofill and every
  // Enter press. Treat a block that follows real content as a line break; a
  // <br> sibling already contributes the newline, so it must not count twice.
  if (node.tagName === "DIV" || node.tagName === "P") {
    return promptBlockPrefix(node) + (inner === "\n" ? "" : inner);
  }
  return inner;
}

// The newline a block element adds in front of its own content: a block holding
// nothing but a <br> is Chrome's placeholder for an extra empty line, while real
// content that follows a <br> continues that line instead of starting a new one.
function promptBlockPrefix(node) {
  const previous = promptSiblingBefore(node);
  if (!previous) return "";
  const inner = [...node.childNodes].map(promptDomText).join("");
  if (inner === "\n" || inner === "") return "\n";
  const previousIsBreak = previous.nodeType === Node.ELEMENT_NODE && previous.tagName === "BR";
  return previousIsBreak ? "" : "\n";
}

function promptEditorText(editor) {
  // Read the children directly. promptDomText() treats a block element that
  // follows content as a new line, and the editor itself is such a block, so
  // calling it on the editor prepended a phantom newline on every extraction.
  const text = [...editor.childNodes].map(promptDomText).join("").replace(/\r/g, "");
  // Chromium keeps a lone BR as the caret container after deleting everything.
  return /^\n*$/.test(text) ? "" : text;
}

function promptTextOffset(editor, targetNode, targetOffset) {
  let length = 0;
  let found = false;
  const visit = node => {
    if (found || !node) return;
    if (node === targetNode) {
      if (node.nodeType === Node.TEXT_NODE) length += node.data.slice(0, targetOffset).replace(PROMPT_CARET_ANCHOR_PATTERN, "").length;
      else if (node.nodeType === Node.ELEMENT_NODE) {
        // The editor itself is a block, but its own text has no leading newline.
        if (node !== editor && (node.tagName === "DIV" || node.tagName === "P")) length += promptBlockPrefix(node).length;
        for (let i = 0; i < Math.min(targetOffset, node.childNodes.length); i++) length += promptDomText(node.childNodes[i]).length;
      }
      found = true;
      return;
    }
    if (node.nodeType === Node.TEXT_NODE) { length += node.data.replace(PROMPT_CARET_ANCHOR_PATTERN, "").length; return; }
    if (node.nodeType !== Node.ELEMENT_NODE) return;
    if (node.classList?.contains("m3td-prompt-media-preview") || node.classList?.contains("m3td-prompt-caret-sentinel")) return;
    if (node.tagName === "BR") { length += 1; return; }
    for (const child of node.childNodes) { visit(child); if (found) break; }
  };
  visit(editor);
  return length;
}

function promptSelectionOffsets(editor, fallback) {
  const selection = window.getSelection();
  if (!selection?.rangeCount || !editor.contains(selection.anchorNode)) return [fallback, fallback];
  const anchor = promptTextOffset(editor, selection.anchorNode, selection.anchorOffset);
  const focus = promptTextOffset(editor, selection.focusNode, selection.focusOffset);
  return [Math.min(anchor, focus), Math.max(anchor, focus)];
}

function promptSetSelection(editor, start, end = start) {
  const selection = window.getSelection();
  if (!selection) return;
  const locate = target => {
    let remaining = Math.max(0, target);
    let location = null;
    const visit = node => {
      if (location) return;
      if (node.classList?.contains("m3td-prompt-media-preview") || node.classList?.contains("m3td-prompt-caret-sentinel")) return;
      if (node.nodeType === Node.TEXT_NODE) {
        const clean = node.data.replace(PROMPT_CARET_ANCHOR_PATTERN, "");
        if (remaining <= clean.length) location = [node, Math.min(remaining, node.data.length)];
        else remaining -= clean.length;
        return;
      }
      if (node.nodeType !== Node.ELEMENT_NODE) return;
      if (node.tagName === "BR") {
        if (remaining === 0) {
          location = [node.parentNode, [...node.parentNode.childNodes].indexOf(node)];
          return;
        }
        // One past the break belongs to whatever follows it. Let the walk carry
        // on so the caret can land inside the next text node (the caret anchor)
        // instead of on a parent offset Chrome would snap back a line.
        remaining -= 1;
        return;
      }
      // A media chip is atomic: never park the caret inside its label, or it
      // looks like you are editing the tag. Boundary positions belong outside.
      if (node.classList?.contains("m3td-prompt-media-token")) {
        const length = promptDomText(node).length;
        const siblings = node.parentNode ? [...node.parentNode.childNodes] : [];
        const index = siblings.indexOf(node);
        const previous = siblings[index - 1];
        const next = siblings[index + 1];
        if (remaining <= 0) {
          // Sit in the text before the chip when there is one; a caret on the
          // element boundary would be painted as tall as the chip itself.
          location = previous?.nodeType === Node.TEXT_NODE
            ? [previous, previous.data.length]
            : [node.parentNode, index];
          return;
        }
        if (remaining === length) {
          location = next?.nodeType === Node.TEXT_NODE
            ? [next, 0]
            : [node.parentNode, index + 1];
          return;
        }
      }
      for (const child of node.childNodes) { visit(child); if (location) return; }
    };
    visit(editor);
    return location || [editor, editor.childNodes.length];
  };
  const [startNode, startOffset] = locate(start);
  const [endNode, endOffset] = locate(end);
  const range = document.createRange();
  range.setStart(startNode, startOffset);
  range.setEnd(endNode, endOffset);
  selection.removeAllRanges();
  selection.addRange(range);
}

// Restoring the caret by offset does not scroll the box: the browser only does
// that for native keystrokes, and the editor rebuilds its markup on every
// structural edit. Pressing Enter on the last visible line therefore left the
// caret one line below the box until the user scrolled by hand.
// All values here are screen pixels: the canvas transform scales the box, so a
// rect cannot be compared against clientHeight directly.
function promptRevealCaret(editor) {
  const selection = window.getSelection();
  if (!selection?.rangeCount || !editor.contains(selection.anchorNode)) return;
  const range = selection.getRangeAt(0).cloneRange();
  range.collapse(true);
  let rect = range.getBoundingClientRect();
  const box = editor.getBoundingClientRect();
  if (!box.height) return;
  const scale = box.height / (editor.offsetHeight || box.height);
  if (!rect || (!rect.height && !rect.width)) {
    // A caret on an empty last line can report a zero-size rect; fall back to
    // the block it sits in, then to the block before it.
    const container = range.startContainer;
    const element = container.nodeType === Node.ELEMENT_NODE ? container : container.parentElement;
    rect = element?.getBoundingClientRect?.() || null;
    if ((!rect || !rect.height) && element?.previousSibling?.getBoundingClientRect) {
      rect = element.previousSibling.getBoundingClientRect();
    }
    if (!rect) return;
  }
  const pad = 6 * scale;
  const top = box.top + editor.clientTop * scale;
  const bottom = top + editor.clientHeight * scale;
  if (rect.bottom > bottom - pad) editor.scrollTop += (rect.bottom - (bottom - pad)) / scale;
  else if (rect.top < top + pad) editor.scrollTop -= ((top + pad) - rect.top) / scale;
}

function resolvePromptMediaEntry(node, type, ordinal) {
  const plan = node?.__m3td?.referencePlan?.();
  if (!plan) return null;
  const list = type === "picture" ? plan.pictures : type === "video" ? plan.videos : plan.audios;
  const entry = list?.[ordinal - 1];
  if (!entry?.file) return null;
  return {
    file: entry.file,
    name: entry.name || entry.file,
    sourceStart: entry.sourceStart,
    kind: entry.kind,
  };
}

const promptVideoThumbs = new Map();
function promptVideoThumbnail(file, onReady, time = 0) {
  if (!file) return null;
  // A long clip contributes several <Video N> pieces; the chip shows the frame
  // at that piece's source start instead of the clip's first frame.
  const start = Math.max(0, Number(time) || 0);
  const key = `${file}@${(Math.round(start * 10) / 10).toFixed(1)}`;
  const cached = promptVideoThumbs.get(key);
  if (typeof cached === "string") return cached || null;
  if (cached === "pending") return null;
  promptVideoThumbs.set(key, "pending");
  const video = document.createElement("video");
  video.muted = true; video.playsInline = true; video.preload = "auto"; video.crossOrigin = "anonymous";
  const finish = value => {
    try { video.removeAttribute("src"); video.load(); } catch (_) {}
    promptVideoThumbs.set(key, value || "");
    if (value && typeof onReady === "function") onReady();
  };
  const capture = () => {
    try {
      const canvas = document.createElement("canvas");
      canvas.width = 64; canvas.height = 64;
      const context = canvas.getContext("2d");
      const ratio = video.videoWidth / Math.max(1, video.videoHeight);
      let sx = 0, sy = 0, sw = video.videoWidth, sh = video.videoHeight;
      if (ratio > 1) { sw = video.videoHeight; sx = (video.videoWidth - sw) / 2; }
      else { sh = video.videoWidth; sy = (video.videoHeight - sh) / 2; }
      context.drawImage(video, sx, sy, sw, sh, 0, 0, 64, 64);
      finish(canvas.toDataURL("image/jpeg", 0.68));
    } catch (_) { finish(""); }
  };
  video.onloadeddata = () => {
    const duration = Number(video.duration) || 0;
    const target = Math.min(start + 0.05, Math.max(0, duration - 0.05));
    if (target > 0.01) {
      video.onseeked = capture;
      try { video.currentTime = target; } catch (_) { capture(); }
    } else capture();
  };
  video.onerror = () => finish("");
  video.src = viewURL(file);
  return null;
}

// One CSS class per decoration kind; the repaint check reads the same table, so a
// new kind only has to be added once.
const PROMPT_DECORATION_CLASSES = {
  media: ".m3td-prompt-media-token",
  control: ".m3td-prompt-control",
  state: ".m3td-prompt-state",
  camera: ".m3td-prompt-camera",
  section: ".m3td-prompt-section",
  speaker: ".m3td-prompt-speaker",
  tag: ".m3td-prompt-tag",
  dialogue: "mark",
};

function promptDecorationKind(element) {
  for (const [kind, selector] of Object.entries(PROMPT_DECORATION_CLASSES)) {
    if (element.matches(selector)) return kind;
  }
  return "";
}

function promptDecorationsOutOfSync(editor, source) {
  const expected = promptDecorations(source).map(item => `${item.kind}${item.missing ? "*" : ""}:${item.raw}`);
  const rendered = [];
  const selector = Object.values(PROMPT_DECORATION_CLASSES).join(", ");
  // Walk every level: Chrome can wrap decorations in paragraph blocks, so a
  // direct-children scan would miss them and force a needless full repaint.
  for (const element of editor.querySelectorAll(selector)) {
    if (element.classList.contains("m3td-prompt-tag") && element.closest(".m3td-prompt-media-token")) continue;
    const kind = promptDecorationKind(element);
    if (!kind) continue;
    // A media chip keeps its label inside the token, so look one level down too.
    const missing = element.classList.contains("m3td-prompt-undefined")
      || !!element.querySelector(".m3td-prompt-undefined");
    rendered.push(`${kind}${missing ? "*" : ""}:${promptDomText(element)}`);
  }
  return expected.length !== rendered.length || expected.some((value, index) => value !== rendered[index]);
}

function renderPromptEditor(editor, node) {
  const state = node.__m3tdPromptEditor;
  if (!state) return;
  const source = String(state.text ?? "");
  const keepFocus = document.activeElement === editor;
  const restore = keepFocus ? promptSelectionOffsets(editor, source.length) : null;
  editor.replaceChildren();
  const appendPlain = text => {
    const parts = text.split("\n");
    parts.forEach((part, index) => {
      if (part) editor.append(document.createTextNode(part));
      if (index < parts.length - 1) editor.append(document.createElement("br"));
    });
  };
  let cursor = 0;
  for (const decoration of promptDecorations(source)) {
    if (decoration.index < cursor) continue;
    if (decoration.index > cursor) appendPlain(source.slice(cursor, decoration.index));
    if (decoration.kind === "dialogue") {
      const mark = document.createElement("mark");
      mark.textContent = decoration.raw;
      editor.append(mark);
    } else if (PROMPT_DECORATION_CLASSES[decoration.kind] && decoration.kind !== "media") {
      const span = document.createElement("span");
      span.className = PROMPT_DECORATION_CLASSES[decoration.kind].slice(1);
      if (decoration.missing) span.classList.add("m3td-prompt-undefined");
      span.textContent = decoration.raw;
      editor.append(span);
    } else {
      const token = document.createElement("span");
      token.className = "m3td-prompt-media-token";
      const entry = resolvePromptMediaEntry(node, decoration.type, decoration.ordinal);
      if (entry) {
        token.title = decoration.type === "audio" && entry.kind === "soundtrack"
          ? `${entry.name} · ${tr("soundtrackTag")}`
          : entry.name;
        let preview;
        if (decoration.type === "audio") {
          preview = document.createElement("span");
          preview.className = "m3td-prompt-media-preview m3td-prompt-audio-preview";
        } else {
          preview = document.createElement("img");
          preview.className = "m3td-prompt-media-preview";
          preview.alt = "";
          if (decoration.type === "video") {
            const thumbnail = promptVideoThumbnail(
              entry.file, () => renderPromptEditor(editor, node), entry.sourceStart
            );
            if (thumbnail) preview.src = thumbnail;
          } else {
            preview.src = viewURL(entry.file);
          }
        }
        preview.contentEditable = "false";
        preview.draggable = false;
        token.append(preview);
      }
      const tag = document.createElement("span");
      tag.className = `m3td-prompt-tag m3td-prompt-tag-${decoration.type}${decoration.missing ? " m3td-prompt-undefined" : ""}`;
      tag.textContent = decoration.raw;
      token.append(tag);
      editor.append(token);
    }
    cursor = decoration.end;
  }
  if (cursor < source.length) appendPlain(source.slice(cursor));
  // A trailing newline renders as a <br>, which leaves no text position on the
  // empty last line, so Chrome parks the caret at the end of the previous line
  // and the next keystroke lands before the break. A zero-width space gives the
  // caret a real home there; prompt text extraction strips it again.
  // A trailing zero-width anchor keeps the caret inside a text node. Empty text
  // keeps the editor childless so the :empty placeholder still shows.
  let caretAnchor = null;
  if (source) {
    caretAnchor = document.createTextNode(PROMPT_CARET_ANCHOR);
    editor.append(caretAnchor);
  }
  editor.classList.toggle("is-empty", !source);
  if (restore) {
    if (document.activeElement !== editor) editor.focus({ preventScroll: true });
    promptSetSelection(editor, restore[0], restore[1]);
    if (caretAnchor && restore[0] === source.length && restore[1] === source.length) {
      const range = document.createRange();
      range.setStart(caretAnchor, 0);
      range.collapse(true);
      const selection = window.getSelection();
      selection?.removeAllRanges();
      selection?.addRange(range);
    }
  }
}

// Repainting decorations rebuilds the editor DOM. Doing that while the caret is
// inside the editor is what used to throw the caret to the very start (and made
// Enter insert a newline at the top), so it only runs once editing pauses or the
// editor loses focus.
const decorationRepaintTimers = new WeakMap();

function repaintPromptDecorations(node) {
  const state = node.__m3tdPromptEditor;
  if (!state?.editor?.isConnected) return;
  // Repaint while focused too, otherwise a tag only lights up after a click
  // somewhere else. renderPromptEditor() re-applies the caret by text offset,
  // so the edit position survives the rebuild. Never touch the DOM mid
  // composition: the IME owns the text until compositionend.
  if (state.composing) return;
  if (promptDecorationsOutOfSync(state.editor, state.text)) renderPromptEditor(state.editor, node);
}

function scheduleDecorationRepaint(node) {
  if (!node.__m3tdPromptEditor?.editor?.isConnected) return;
  const previous = decorationRepaintTimers.get(node);
  if (previous) clearTimeout(previous);
  const timer = setTimeout(() => {
    decorationRepaintTimers.delete(node);
    repaintPromptDecorations(node);
  }, 250);
  decorationRepaintTimers.set(node, timer);
}

// ---- Prompt health check -----------------------------------------------------
// The H3 guides constrain the prompt in ways a human misses while writing:
// section order, cut times inside the generated duration, a closed label set and
// <d> only inside the description. Nothing here rewrites the text; the strip
// under the editor just lists what looks wrong.
const PROMPT_REF_SECTIONS = ["subject_definitions", "summary", "retention_analysis", "detailed_description", "overall_soundscape", "non_diegetic_music"];
const PROMPT_BASE_SECTIONS = ["integrated_multimodal_description", "overall_soundscape", "non_diegetic_music"];

function promptSectionSpans(text) {
  const spans = [];
  let offset = 0;
  for (const line of text.split("\n")) {
    const match = /^[ \t]*([a-z_]{3,40})[ \t]*[:：]/.exec(line);
    if (match && (PROMPT_REF_SECTIONS.includes(match[1]) || PROMPT_BASE_SECTIONS.includes(match[1]))) {
      // `body` starts right after the colon: content often sits on the same line
      // as the header ("overall_soundscape: rain ..."), not on the next one.
      spans.push({ name: match[1], index: offset + match.index, body: offset + match[0].length });
    }
    offset += line.length + 1;
  }
  return spans;
}

function promptSectionBody(text, spans, name) {
  const index = spans.findIndex(span => span.name === name);
  if (index < 0) return "";
  return text.slice(spans[index].body, spans[index + 1]?.index ?? text.length);
}

function promptLabelSet(text) {
  return new Set([...text.matchAll(/<([A-Za-z]+)[ \t]+(\d+)>/g)].map(match => `<${match[1]} ${match[2]}>`));
}

// Labels compare by their exact spelling (case included) with spaces collapsed,
// so "<subject 1>" does not silently match the defined "<Subject 1>".
function promptLabelKey(label) {
  return label.replace(/[ \t]+/g, " ").trim();
}

function promptDefinedLabels(text) {
  const definitions = promptSectionBody(text, promptSectionSpans(text), "subject_definitions");
  return new Set([...promptLabelSet(definitions)].map(promptLabelKey));
}

function promptFormatTime(value) {
  const minutes = Math.floor(value / 60);
  const seconds = (value - minutes * 60).toFixed(3).padStart(6, "0");
  return `${String(minutes).padStart(2, "0")}:${seconds}`;
}

function promptIssues(text, seconds, plan = null) {
  const issues = [];
  const add = (level, message) => issues.push({ level, message });
  const spans = promptSectionSpans(text);
  const names = spans.map(span => span.name);
  const isBase = names.includes("integrated_multimodal_description");
  const description = isBase ? "integrated_multimodal_description" : "detailed_description";

  if (names.length) {
    const expected = isBase ? PROMPT_BASE_SECTIONS : PROMPT_REF_SECTIONS;
    const missing = expected.filter(name => !names.includes(name));
    if (missing.length) add("error", `缺少段落 ${missing.join("、")}`);
    const duplicated = [...new Set(names.filter((name, index) => names.indexOf(name) !== index))];
    if (duplicated.length) add("error", `段落重复 ${duplicated.join("、")}`);
    const sequence = names.filter((name, index) => index === 0 || name !== names[index - 1])
      .map(name => expected.indexOf(name)).filter(index => index >= 0);
    if (sequence.some((value, index) => index && value < sequence[index - 1])) {
      add("error", `段落顺序应为 ${expected.join(" → ")}`);
    }
  }
  // A base-mode prompt starts with the alignment instruction, then one blank line.
  const firstLine = text.split("\n")[0].trim();
  if (firstLine && !spans.some(span => span.index === 0) && text.split("\n")[1]?.trim()) {
    add("warn", "首行指令后应空一行");
  }

  // A label that points past the end of the asset library silently renders as a
  // dead chip: H3 never receives that reference, so the shot comes out wrong.
  // The plan already applies the H3 caps, so an ordinal can be "present but
  // capped" (asset exists, not sent) or genuinely missing; report them apart.
  if (plan) {
    const labels = { picture: "参考图片", video: "参考视频", audio: "参考音频" };
    // Audio ordinals use the official order: paired video soundtracks first,
    // then standalone assets.  available and nominal include both, while
    // overflow only counts standalone assets against the three-audio cap.
    const available = {
      picture: plan.pictures.length,
      video: plan.videos.length,
      audio: plan.audios.length,
    };
    const nominal = {
      picture: plan.nominal.pictures,
      video: plan.nominal.videos,
      audio: plan.nominal.audios,
    };
    const limits = {
      picture: plan.limits.pictures,
      video: plan.limits.videos,
      audio: plan.limits.audios,
    };
    const mediaItems = promptMediaMatches(text);
    const seen = new Set();
    const capped = [];
    const missing = [];
    for (const item of mediaItems) {
      if (item.ordinal <= available[item.type]) continue;
      const key = `${item.type}:${item.ordinal}`;
      if (seen.has(key)) continue;
      seen.add(key);
      (item.ordinal <= nominal[item.type] ? capped : missing).push(item);
    }
    for (const item of capped.slice(0, 4)) {
      add("error", tr("promptOverCap", { label: item.raw, limit: limits[item.type] }));
    }
    for (const item of missing.slice(0, 4)) {
      add("error", available[item.type] > 0
        ? `${item.raw} 没有对应素材（${labels[item.type]}只有 ${available[item.type]} 个）`
        : `${item.raw} 没有对应素材（还没有${labels[item.type]}）`);
    }
    const omitted = capped.length + missing.length
      - Math.min(4, capped.length) - Math.min(4, missing.length);
    if (omitted > 0) add("error", `另有 ${omitted} 个标签不可用`);

    // References the backend will actually send but the prompt never mentions.
    // Over-cap assets are not in the plan, so they are excluded here; the cap
    // warnings above already explain why they are missing.
    if (text.trim()) {
      const cited = new Set(mediaItems.map(item => `${item.type}:${item.ordinal}`));
      const typeNames = { picture: "Picture", video: "Video", audio: "Audio" };
      const unused = [
        ...plan.pictures.map(item => ({ type: "picture", ordinal: item.ordinal })),
        ...plan.videos.map(item => ({ type: "video", ordinal: item.ordinal })),
        ...plan.audios.map(item => ({ type: "audio", ordinal: item.ordinal })),
      ].filter(item => !cited.has(`${item.type}:${item.ordinal}`));
      for (const item of unused.slice(0, 4)) {
        add("warn", tr("unusedReference", { label: `<${typeNames[item.type]} ${item.ordinal}>` }));
      }
      if (unused.length > 4) {
        add("warn", tr("unusedReferencesMore", { count: unused.length - 4 }));
      }
    }
  }

  const times = [];
  // The lookahead stops the match at the next "[Shot N]" marker: the description
  // is usually one long line, so a plain "[^\n]*?" would hand Shot 2's cut time
  // to Shot 1 and report a phantom error.
  for (const match of text.matchAll(/\[Shot[ \t]+(\d+)\](?:(?!\[Shot[ \t]*\d+\])[^\n])*?At[ \t]+(\d{1,3}):([0-5]\d)\.(\d{3})/g)) {
    times.push({
      shot: Number(match[1]),
      value: Number(match[2]) * 60 + Number(match[3]) + Number(match[4]) / 1000,
    });
  }
  if (times.some(item => item.shot === 1)) add("error", "[Shot 1] 不应带时间码");
  for (let index = 1; index < times.length; index++) {
    if (times[index].value <= times[index - 1].value) {
      add("error", `[Shot ${times[index].shot}] 时间码没有递增`);
    }
  }
  const latest = times.reduce((max, item) => Math.max(max, item.value), 0);
  if (seconds > 0 && latest >= seconds) {
    add("error", `时间码 ${promptFormatTime(latest)} 超出生成时长 ${seconds.toFixed(1)}s`);
  }

  const definitions = promptSectionBody(text, spans, "subject_definitions");
  const defined = promptLabelSet(definitions);
  const used = new Set();
  for (const span of spans) {
    if (span.name === "subject_definitions") continue;
    for (const label of promptLabelSet(promptSectionBody(text, spans, span.name))) used.add(label);
  }
  const unknown = [...used].filter(label => !defined.has(label));
  if (defined.size && unknown.length) {
    const hints = unknown.slice(0, 3).map(label => {
      const similar = [...defined].find(item => item.toLowerCase() === label.toLowerCase());
      return similar ? `${label}（应为 ${similar}）` : label;
    });
    add("error", `未定义的标签 ${hints.join("、")}`);
  }
  const tracked = [...definitions.matchAll(/^[ \t]*<([A-Za-z]+)[ \t]+(\d+)>/gm)].map(match => `<${match[1]} ${match[2]}>`);
  const retention = promptSectionBody(text, spans, "retention_analysis");
  if (tracked.length) {
    const unlisted = tracked.filter(label => !retention.includes(label));
    if (unlisted.length) add("warn", `retention_analysis 缺少 ${unlisted.slice(0, 3).join("、")}`);
  }
  if (/\(\s*S\d/i.test(retention)) add("error", "retention_analysis 里不应出现 (Sx)");
  for (const name of ["summary", "retention_analysis", "overall_soundscape", "non_diegetic_music"]) {
    if (promptSectionBody(text, spans, name).includes("<d>")) add("error", `${name} 里不应出现 <d> 对白`);
  }

  for (const [name, limit] of [["overall_soundscape", 4], ["non_diegetic_music", 3]]) {
    const value = promptSectionBody(text, spans, name).trim();
    if (!value || value === "N/A") continue;
    const sentences = (value.match(/[.!?]+(?=\s|$)/g) || []).length;
    if (sentences > limit) add("warn", `${name} ${sentences} 句（建议 1–${limit} 句）`);
  }
  return issues;
}

