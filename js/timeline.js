  // Copy the source video's own resolution onto the clip's reference canvas.
  // Older clips never stored their source size, so fetch it once on demand.
  async applySourceSize(clip) {
    if(!clip)return;
    if(!clip.sourceWidth||!clip.sourceHeight){
      this.setStatus(tr("sourceSizeReading"),0.3);
      try{
        const response=await api.fetchApi("/h3_director_custom/media_info",{
          method:"POST",headers:{"Content-Type":"application/json"},
          body:JSON.stringify({filename:clip.file,kind:"video"}),
        });
        const info=await responseJSON(response);
        if(response.ok&&info?.width&&info?.height){
          clip.sourceWidth=Math.round(num(info.width,0));
          clip.sourceHeight=Math.round(num(info.height,0));
        }
      }catch(error){
        console.warn("[MiniMaxH3TimelineDirector] source size lookup failed",error);
      }
    }
    if(!clip.sourceWidth||!clip.sourceHeight){this.setStatus(tr("sourceSizeFailed"));return;}
    clip.referenceWidth=alignReferenceDimension(clip.sourceWidth);
    clip.referenceHeight=alignReferenceDimension(clip.sourceHeight);
    this.sync();this.render();
    this.setStatus(tr("sourceSizeApplied",{width:clip.referenceWidth,height:clip.referenceHeight}));
  }

  // Width/height are often linked from a ResolutionSelector, so the node's own
  // widget values can be stale. Mirror the selector's formula to show the size
  // the text encoder will actually receive.
  generationSize() {
    const widgetValue = name => this.node.widgets?.find(w => w.name === name)?.value;
    let width = Math.max(0, Math.round(num(widgetValue("width"), 0)));
    let height = Math.max(0, Math.round(num(widgetValue("height"), 0)));
    const graph = this.node.graph;
    const links = graph?.links;
    const input = ["width", "height"]
      .map(name => this.node.inputs?.find(item => item.name === name))
      .find(item => item?.link != null)
      || this.node.inputs?.find(item => item.name === "width");
    const linkId = input?.link;
    if (linkId == null) return { width, height };
    const link = typeof links?.get === "function" ? links.get(linkId) : links?.[linkId];
    const origin = link ? graph?.getNodeById?.(link.origin_id) : null;
    if (origin?.type !== "ResolutionSelector") return { width, height };
    const originValue = name => origin.widgets?.find(w => w.name === name)?.value;
    const ratio = String(originValue("aspect_ratio") || "").match(/^(\d+):(\d+)/);
    const megapixels = Number(originValue("megapixels"));
    const multiple = Math.max(1, Math.round(Number(originValue("multiple")) || 8));
    if (!ratio || !Number.isFinite(megapixels) || megapixels <= 0) return { width, height };
    const ratioWidth = Number(ratio[1]);
    const ratioHeight = Number(ratio[2]);
    const scale = Math.sqrt(megapixels * 1024 * 1024 / (ratioWidth * ratioHeight));
    width = roundHalfEven(ratioWidth * scale / multiple) * multiple;
    height = roundHalfEven(ratioHeight * scale / multiple) * multiple;
    return { width, height };
  }

