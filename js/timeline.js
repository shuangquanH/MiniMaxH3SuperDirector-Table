function bindRichPromptEditor(node, promptWidget, editor, textarea) {
  const state = node.__m3tdPromptEditor;
  // Chrome's own undo stack dies every time the decoration repaint rebuilds the
  // editor DOM, which is why Ctrl+Z did nothing while typing and could only be
  // "undone" as a graph action afterwards. The editor keeps its own snapshots:
  // one step per edit burst, so a burst of typing undoes as a single change.
  const history = { undo: [], redo: [] };
  let baseline = { text: String(state?.text ?? ""), caret: 0 };
  let lastRecordAt = 0;
  const caretOffset = () => promptSelectionOffsets(editor, promptEditorText(editor).length)[0];
  const remember = () => { if (state) baseline = { text: String(state.text ?? ""), caret: caretOffset() }; };
  const pushUndo = () => {
    const top = history.undo[history.undo.length - 1];
    if (top && top.text === baseline.text) return;
    history.undo.push({ ...baseline });
    if (history.undo.length > 100) history.undo.shift();
    history.redo.length = 0;
  };
  // A new undo step opens only after 600 ms of quiet, so a burst of typing (or
  // one IME composition) collapses into a single entry.
  const beginUndoStep = () => {
    if (Date.now() - lastRecordAt > 600) {
      pushUndo();
      lastRecordAt = Date.now();
    }
  };
  const restore = entry => {
    state.text = entry.text;
    renderPromptEditor(editor, node);
    const caret = Math.min(entry.caret, entry.text.length);
    promptSetSelection(editor, caret, caret);
    editor.focus({ preventScroll: true });
    promptRevealCaret(editor);
    commit();
    // 0 closes the current grouping window: the next keystroke opens a new step.
    lastRecordAt = 0;
  };
  const stepBack = () => {
    if (!history.undo.length) return false;
    history.redo.push({ text: promptEditorText(editor), caret: caretOffset() });
    restore(history.undo.pop());
    return true;
  };
  const stepForward = () => {
    if (!history.redo.length) return false;
    history.undo.push({ text: promptEditorText(editor), caret: caretOffset() });
    restore(history.redo.pop());
    return true;
  };
  const handleEditShortcut = event => {
    if (!(event.ctrlKey || event.metaKey) || event.altKey) return false;
    const key = String(event.key || "").toLowerCase();
    if (key !== "z" && key !== "y") return false;
    // Always swallow the native undo: after a re-render it restores stale DOM
    // instead of text, and it must never reach the canvas undo either.
    event.preventDefault();
    event.stopPropagation();
    if (key === "y" || event.shiftKey) stepForward();
    else stepBack();
    return true;
  };
  const commit = () => {
    if (!state) return;
    const text = promptEditorText(editor);
    state.text = text;
    editor.classList.toggle("is-empty", !text);
    refreshPromptCheck(node);
    remember();
    if (String(promptWidget.value ?? "") === text) return;
    promptWidget.value = text;
    // Only mirror the text. Dispatching an input event on the hidden textarea
    // makes Vue re-render the widget subtree, which detaches this editor and
    // resets the caret to the start of the prompt.
    if (textarea) textarea.value = text;
    node.__m3td?.sync?.();
    markWorkflowModified();
    // Decorations are repainted on a debounce, never synchronously: rebuilding
    // the DOM mid-keystroke is what used to move the caret to the very start.
    scheduleDecorationRepaint(node);
  };
  // The workflow can replace the text under us (load, undo of a graph change),
  // and those states must not be reachable through the edit history.
  state.resetHistory = text => {
    history.undo.length = 0;
    history.redo.length = 0;
    baseline = { text: String(text ?? ""), caret: 0 };
  };
  // The panel's "clear prompt" button edits the model, not the DOM: going through
  // commit() keeps widget value, decorations, dirty flag and undo stack aligned.
  // The whole swap is one edit, so a single Ctrl+Z brings the previous text back.
  state.setAll = text => {
    pushUndo();
    state.text = String(text ?? "");
    renderPromptEditor(editor, node);
    commit();
  };
  // Insert plain text at the caret and repaint. Used for Enter and paste so the
  // DOM never grows the <div> paragraphs Chrome would otherwise create.
  const insertPlain = replacement => {
    pushUndo();
    lastRecordAt = Date.now();
    const current = promptEditorText(editor);
    const [start, end] = promptSelectionOffsets(editor, current.length);
    state.text = current.slice(0, start) + replacement + current.slice(end);
    renderPromptEditor(editor, node);
    const caret = start + replacement.length;
    promptSetSelection(editor, caret, caret);
    // Enter at the bottom of the box, or a paste that adds lines: the caret has
    // to follow, otherwise it is typed into a line the user cannot see.
    promptRevealCaret(editor);
    commit();
  };
  let composing = false;
  editor.addEventListener("compositionstart", () => {
    composing = true;
    state.composing = true;
    beginUndoStep();
  });
  editor.addEventListener("compositionend", () => {
    composing = false;
    state.composing = false;
    commit();
    scheduleDecorationRepaint(node);
  });
  editor.addEventListener("input", () => {
    if (composing) return;
    beginUndoStep();
    commit();
  });
  // Enter is handled by hand: preventDefault cancels the input event Chrome
  // would fire, and its own paragraph block leaves the caret on a parent offset
  // that paints one line too low (a newline at the top, or a double line).
  // insertPlain re-renders, restores the caret inside the new line's anchor and
  // commits, so the newline always reaches the widget exactly once.
  editor.addEventListener("beforeinput", event => {
    if (!["insertParagraph", "insertLineBreak"].includes(event.inputType)) return;
    event.preventDefault();
    insertPlain("\n");
  });
  // Let the browser insert its own paragraph / line break. promptDomText turns
  // the resulting blocks back into newlines, which keeps the caret native and
  // avoids the fragile offset math a manual re-render would need.
  editor.addEventListener("keydown", event => {
    if (handlePanelSaveShortcut(event)) return;
    if (handleEditShortcut(event)) return;
    event.stopPropagation();
  });
  for (const type of ["keyup", "keypress"]) editor.addEventListener(type, event => event.stopPropagation());
  // Wheel over the prompt scrolls the text while it is focused and has hidden
  // lines; otherwise the event is left alone so the canvas keeps zooming. It has
  // to be a window-capture listener: ComfyUI's canvas wheel bridge runs in the
  // document capture phase and turns every wheel into a zoom before the editor
  // ever sees it, which is why the scrollbar used to be the only way down a long
  // prompt. The listener removes itself once the editor is gone.
  const onPromptWheel = event => {
    if (!editor.isConnected) { window.removeEventListener("wheel", onPromptWheel, true); return; }
    if (event.target !== editor && !editor.contains(event.target)) return;
    // Only while the caret is in the box: hovering an unfocused prompt keeps the
    // canvas zoom, which is what the pointer being "outside" means here.
    if (document.activeElement !== editor) return;
    const limit = editor.scrollHeight - editor.clientHeight;
    const unit = event.deltaMode === 1 ? 18 : event.deltaMode === 2 ? editor.clientHeight : 1;
    const delta = event.deltaY * unit;
    if (limit <= 1 || !delta) return;
    // Swallow the wheel even at either end: while the caret is in the box a
    // stray zoom is far more annoying than a scroll that stops at the edge.
    event.preventDefault();
    event.stopImmediatePropagation();
    editor.scrollTop += delta;
  };
  window.addEventListener("wheel", onPromptWheel, { capture: true, passive: false });
  editor.addEventListener("pointerdown", event => event.stopPropagation());
  // A middle press over the box belongs to the canvas pan. Cancelling the default
  // action keeps Chrome from focusing the editor and moving the caret, which used
  // to drop an idle prompt into edit mode just because the user panned over it.
  editor.addEventListener("mousedown", event => { if (event.button === 1) event.preventDefault(); });
  // Copy the model text, not the rendered DOM: chips and the caret anchor are
  // presentation only and must not leak into the clipboard.
  editor.addEventListener("copy", event => {
    const text = promptEditorText(editor);
    const [start, end] = promptSelectionOffsets(editor, text.length);
    if (start === end) return;
    event.preventDefault();
    event.clipboardData?.setData("text/plain", text.slice(start, end));
  });
  editor.addEventListener("paste", event => {
    event.preventDefault();
    const text = (event.clipboardData || window.clipboardData)?.getData("text") || "";
    if (text) insertPlain(text.replace(/\r\n?/g, "\n"));
  });
  // Once editing stops, paint the chips so the user sees the decorated prompt.
  editor.addEventListener("blur", () => {
    setTimeout(() => repaintPromptDecorations(node), 0);
  });
}

