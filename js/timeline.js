// A clip can use only part of its source file (trimStart + duration). Map a
// column of the clip's on-screen waveform to the matching source sample so a
// trimmed or split clip draws the peaks it actually plays.
function waveformPeakAt(peaks, x, width, trimStart, duration, sourceDuration) {
  if (!peaks?.length) return 0;
  const span = Math.max(1, num(width, 1));
  const source = num(sourceDuration, 0);
  const start = Math.max(0, num(trimStart, 0));
  const length = Math.max(0, num(duration, 0));
  let from = 0;
  let to = 1;
  // If the stored source duration cannot contain the visible interval (older
  // clips defaulted it to the trimmed length), fall back to the whole peaks
  // array instead of drawing a misleading partial range.
  if (source > 0 && length > 0 && source + 1e-6 >= start + length) {
    from = clamp(start / source, 0, 1);
    to = clamp((start + length) / source, from, 1);
  }
  const fraction = from + (clamp(num(x, 0), 0, span) / span) * (to - from);
  const index = clamp(Math.floor(fraction * peaks.length), 0, peaks.length - 1);
  return clamp(num(peaks[index], 0), 0, 1);
}
// "Update segments" keeps the user oriented: when segments are added, select
// the first new one; when removed, select the last remaining one; otherwise
// keep the current segment.
function nextActiveSegment(previousCount, previousActive, count) {
  if (count > previousCount) return previousCount;
  if (count < previousCount) return count - 1;
  return Math.min(previousActive, count - 1);
}
