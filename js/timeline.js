function refreshPromptCheck(node) {
  const host = node.__m3tdPromptCheck;
  const editor = node.__m3tdPromptEditor?.editor;
  if (!host || !editor?.isConnected) return;
  const text = promptEditorText(editor);
  // Duration lives in the cyan timeline range only; the node has no length widget.
  const state = node.__m3td?.state;
  const seconds = Number(state?.selection?.duration) || 0;
  const plan = node.__m3td?.referencePlan?.() || null;
  const planKey = plan
    ? `${plan.pictures.length}/${plan.videos.length}/${plan.audios.length}/`
      + `${plan.overflow.pictures}/${plan.overflow.videos}/${plan.overflow.audios}`
    : "-";
  // The height sync runs this again a frame later; bail out when nothing changed
  // so the two never chase each other. Adding, reordering or capping an asset
  // changes the verdict too, hence the key below.
  if (host.__m3tdText === text && host.__m3tdSeconds === seconds && host.__m3tdPlanKey === planKey) return;
  host.__m3tdText = text;
  host.__m3tdSeconds = seconds;
  host.__m3tdPlanKey = planKey;
  const issues = [
    ...referenceCapIssues(plan),
    ...(text.trim() ? promptIssues(text, seconds, plan) : []),
  ];
  if (!issues.length) {
    host.hidden = true;
    host.textContent = "";
    host.removeAttribute("title");
  } else {
    const errors = issues.filter(issue => issue.level === "error").length;
    host.hidden = false;
    host.className = `m3td-prompt-check ${errors ? "is-error" : "is-warn"}`;
    const head = errors ? `${errors} 项错误` : `${issues.length} 项提醒`;
    const rest = errors && issues.length > errors ? ` · ${issues.length - errors} 项提醒` : "";
    // Every issue is listed; the strip wraps instead of truncating, and the node
    // grows to fit it.
    const list = issues.map(issue => `${issue.level === "error" ? "✗" : "!"} ${issue.message}`).join("；");
    host.textContent = `提示词体检：${head}${rest} — ${list}`;
    host.title = issues.map(issue => `${issue.level === "error" ? "✗" : "!"} ${issue.message}`).join("\n");
  }
  // The strip is a flex child of the prompt area, so a new line simply takes
  // room from the editor; no relayout request is needed (and asking for one here
  // used to feed a measure → restyle → measure loop on every zoom step).
}

