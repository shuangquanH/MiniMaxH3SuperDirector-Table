  async addFile(kind,file) {
    if(this.uploading)return;
    // The backend drops anything past these caps; refuse the upload instead of
    // letting an asset sit in the timeline that H3 will never see. Videos are
    // allowed past the cap because they can still guide without a <Video N>.
    if(kind==="image"&&this.state.images.length>=MAX_REFERENCE_IMAGES){
      this.setStatus(tr("tooManyImages",{limit:MAX_REFERENCE_IMAGES}));
      return;
    }
    if(kind==="audio"&&this.state.audios.length>=MAX_REFERENCE_AUDIOS){
      this.setStatus(tr("tooManyAudios",{limit:MAX_REFERENCE_AUDIOS}));
      return;
    }
    this.uploading=true;
    try{
      if(file.size<=0)throw new Error(tr("emptyFile"));
      if(file.size>MAX_UPLOAD_BYTES)throw new Error(tr("tooLarge"));
      const serverName=`${Date.now()}_${Math.random().toString(36).slice(2,7)}_${file.name.replace(/[^\w.()\-\u4e00-\u9fff]+/gu,"_")}`;
      const data=new FormData();
      data.append("image",file,serverName);
      data.append("type","input");
      data.append("subfolder",UPLOAD_SUBFOLDER);
      this.setStatus(tr("uploading",{name:file.name}),0.15);
      const uploadResponse=await api.fetchApi("/upload/image",{method:"POST",body:data});
      const uploadPayload=await responseJSON(uploadResponse);
      if(!uploadResponse.ok){
        const hint=uploadResponse.status===413?tr("uploadSizeHint"):"";
        throw new Error(uploadPayload.error||tr("uploadFailed",{status:uploadResponse.status,hint}));
      }
      const uploadedFile=uploadedRelativePath(uploadPayload);
      this.setStatus(tr("checking",{name:file.name}),0.75);
      const infoResponse=await api.fetchApi("/h3_director_custom/media_info",{
        method:"POST",
        headers:{"Content-Type":"application/json"},
        body:JSON.stringify({filename:uploadedFile,kind}),
      });
      const info=await responseJSON(infoResponse);
      if(!infoResponse.ok||info.error)throw new Error(info.error||tr("mediaCheckFailed",{status:infoResponse.status}));
      if(kind==="video"){
        if(!info.hasVideo)throw new Error(tr("noVideoTrack"));
        const start=this.state.videoClips.reduce((m,c)=>Math.max(m,c.start+c.duration),0);
        const duration=Math.max(5/24,num(info.duration,5));
        // Default the reference canvas to the source video's own resolution so a
        // fresh clip is never silently downscaled to the generation size.
        const sourceWidth=Math.max(0,Math.round(num(info.width,0)));
        const sourceHeight=Math.max(0,Math.round(num(info.height,0)));
        const nodeWidth=num(this.node.widgets?.find(widget=>widget.name==="width")?.value,0);
        const nodeHeight=num(this.node.widgets?.find(widget=>widget.name==="height")?.value,0);
        const referenceWidth=alignReferenceDimension(sourceWidth||nodeWidth||832);
        const referenceHeight=alignReferenceDimension(sourceHeight||nodeHeight||480);
        const clip={id:uid(),file:info.filename,name:file.name,start,duration,trimStart:0,sourceDuration:duration,hasAudio:!!info.hasAudio,referenceMode:"edit",referenceWidth,referenceHeight,sourceWidth,sourceHeight,peaks:info.peaks||[],proxy:""};
        this.state.videoClips.push(clip);this.selectedId=clip.id;
      }else if(kind==="image"){
        const asset={id:uid(),file:info.filename,name:file.name,width:info.width||0,height:info.height||0};
        this.state.images.push(asset);
      }else {
        if(!info.hasAudio)throw new Error(tr("noAudioTrack"));
        const asset={id:uid(),file:info.filename,name:file.name,duration:info.duration||0,trimStart:0};
        this.state.audios.push(asset);
      }
      this.sync();this.render();this.setStatus(tr("addedFile",{name:file.name}),1);
    }catch(error){console.error("[MiniMaxH3TimelineDirector]",error);this.setStatus(tr("failed",{error:error.message}),0);}
    finally{this.uploading=false;setTimeout(()=>{this.progress.style.width="0";},800);}
  }

