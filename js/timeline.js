// The backend resolves these sizes with Python's round(), which sends exact
// halves to the nearest even integer. Mirror it so the panel shows the size the
// text encoder will actually receive.
const roundHalfEven = value => {
  const floor = Math.floor(value);
  const diff = value - floor;
  if (diff > 0.5) return floor + 1;
  if (diff < 0.5) return floor;
  return floor % 2 === 0 ? floor : floor + 1;
};
const REFERENCE_IMAGE_SHORT_EDGE = 2048;
const REFERENCE_CANVAS_MULTIPLE = 32;

// Mirror of _ref_image_target_size() in director.py; roundHalfEven keeps the
// panel's submitted-size label identical to the size the encoder receives.
function referenceImageSize(image, width, height, mode) {
  const imageWidth = Math.round(num(image?.width, 0));
  const imageHeight = Math.round(num(image?.height, 0));
  const generationWidth = Math.max(1, Math.round(num(width, 0)));
  const generationHeight = Math.max(1, Math.round(num(height, 0)));
  if (imageWidth < 1 || imageHeight < 1) return null;
  const multiple = REFERENCE_CANVAS_MULTIPLE;
  const scaled = scale => [
    Math.max(multiple, roundHalfEven(imageWidth * scale / multiple) * multiple),
    Math.max(multiple, roundHalfEven(imageHeight * scale / multiple) * multiple),
  ];
  const matchScale = Math.min(1, Math.sqrt(
    Math.max(1, generationWidth * generationHeight) / (imageWidth * imageHeight)
  ));
  const maxScale = Math.min(1, REFERENCE_IMAGE_SHORT_EDGE / Math.min(imageWidth, imageHeight));
  const matchSize = scaled(matchScale);
  const maxSize = scaled(maxScale);
  if (mode === "match") return matchSize;
  if (mode === "average") {
    return [
      Math.max(multiple, roundHalfEven(((matchSize[0] + maxSize[0]) / 2) / multiple) * multiple),
      Math.max(multiple, roundHalfEven(((matchSize[1] + maxSize[1]) / 2) / multiple) * multiple),
    ];
  }
  return maxSize;
}
